package ru.ynovka.myShore.text

/**
 * Таблица ширин символов в пикселях для кастомного шрифта ресурспака.
 * Портирована из Denizen-процедуры DialogueAudiuSizeChars (таблица без #).
 *
 * Порядок определения в buildMap важен: последнее значение для дублирующегося ключа побеждает.
 * Дублей нет — каждый символ ровно в одной группе.
 */
object CharWidth {

    private val table: Map<Char, Int> = buildMap {

        // ── Width 2 ─────────────────────────────────────────────────────────
        "!',.;:i\u2019".forEach { put(it, 2) }   // ' ! , . ; : i '

        // ── Width 3 ─────────────────────────────────────────────────────────
        "`▪l".forEach { put(it, 3) }

        // ── Width 4 ─────────────────────────────────────────────────────────
        " ()*[]It{}◘".forEach { put(it, 4) }     // (space) включён

        // ── Width 5 ─────────────────────────────────────────────────────────
        "fk".forEach { put(it, 5) }               // Latin
        "гк".forEach { put(it, 5) }               // Кириллица строчная г к

        // ── Width 6 ─────────────────────────────────────────────────────────
        // Символы и цифры
        "+-±#%/?■0123456789\$=^_∈≥≤÷ψ".forEach { put(it, 6) }

        // Latin строчные: всё кроме f(5) i(2) k(5) l(3) t(4)
        "abcdeghj mnopqrsuvwxyz".replace(" ", "").forEach { put(it, 6) }

        // Latin прописные: всё кроме I(4); W не в Denizen-таблице → даём 6 как дефолт
        "ABCDEFGHJKLMNOPQRSTUVWXYZmM".forEach { put(it, 6) }
        // Примечание: m/M продублированы в Denizen явно в конце таблицы 6 — оставляем

        // Кириллица строчная: без г к (5), ю (8), ы щ (7)
        "абвеёжзийлмнопрстуфхцчшьэя".forEach { put(it, 6) }

        // Кириллица прописная: без Д Ц (7), Ж Ф Ш (8), Щ (9), Ы Ю (8), Ъ (7)
        "АБВГЕЗИЙКЛНОПРСТУХЧЬЭЯМ".forEach { put(it, 6) }

        // ── Width 7 ─────────────────────────────────────────────────────────
        "~√ъ@«»≡≈Ω✔ДЦЪдыщ".forEach { put(it, 7) }
        put('\uD83D', 7)   // суррогатная пара 🔥 — старший
        put('\uDD25', 7)   // суррогатная пара 🔥 — младший

        // ── Width 8 ─────────────────────────────────────────────────────────
        "❤⌀★☠⏻⌚ЖФШюЫЮ".forEach { put(it, 8) }

        // ── Width 9 ─────────────────────────────────────────────────────────
        put('Щ', 9)

        // ── Width 10 ────────────────────────────────────────────────────────
        "⚠☯☒☐☑№".forEach { put(it, 10) }
    }

    /** Возвращает пиксельную ширину символа. Для неизвестных символов — 6 (дефолт). */
    fun of(char: Char): Int = table[char] ?: 6
}